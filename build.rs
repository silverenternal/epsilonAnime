use serde::Deserialize;
use std::env;
use std::fs;
use std::path::PathBuf;

#[derive(Debug, Deserialize)]
struct Variant {
    name: String,
    kernel: String,
    palette: String,
    weight: f32,
}

#[derive(Debug, Deserialize)]
struct AnimFile {
    variant: Vec<Variant>,
}

#[derive(Debug, Deserialize)]
struct Palette {
    name: String,
    colors: Vec<String>,
}

#[derive(Debug, Deserialize)]
struct PaletteFile {
    palette: Vec<Palette>,
}

#[derive(Debug, Deserialize)]
struct SpectralMode {
    kx: f32,
    ky: f32,
    phase: f32,
    speed: f32,
    weight: f32,
}

#[derive(Debug, Deserialize)]
struct SpectralFile {
    mode: Vec<SpectralMode>,
}

const LUT_SIZE: usize = 4096;

fn parse_hex(s: &str) -> [u8; 3] {
    let h = s.trim_start_matches('#');
    [
        u8::from_str_radix(&h[0..2], 16).expect("bad hex"),
        u8::from_str_radix(&h[2..4], 16).expect("bad hex"),
        u8::from_str_radix(&h[4..6], 16).expect("bad hex"),
    ]
}

fn main() {
    println!("cargo:rerun-if-changed=specs/animations.toml");
    println!("cargo:rerun-if-changed=specs/palettes.toml");
    println!("cargo:rerun-if-changed=specs/spectral_modes.toml");
    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("math_tables.rs");

    let anims: AnimFile =
        toml::from_str(&fs::read_to_string("specs/animations.toml").expect("read animations.toml"))
            .expect("parse animations.toml");
    let palettes: PaletteFile =
        toml::from_str(&fs::read_to_string("specs/palettes.toml").expect("read palettes.toml"))
            .expect("parse palettes.toml");
    let spectral: SpectralFile = toml::from_str(
        &fs::read_to_string("specs/spectral_modes.toml").expect("read spectral_modes.toml"),
    )
    .expect("parse spectral_modes.toml");

    let mut src = String::new();
    src.push_str("// generated by build.rs\n");
    src.push_str(&format!("pub const SIN_LUT: [f32; {LUT_SIZE}] = [\n"));
    for i in 0..LUT_SIZE {
        let v = (std::f64::consts::TAU * i as f64 / LUT_SIZE as f64).sin();
        src.push_str(&format!("{v:.9}f32,"));
        if i % 8 == 7 {
            src.push('\n');
        }
    }
    src.push_str("];\n");
    src.push_str(&format!("pub const COS_LUT: [f32; {LUT_SIZE}] = [\n"));
    for i in 0..LUT_SIZE {
        let v = (std::f64::consts::TAU * i as f64 / LUT_SIZE as f64).cos();
        src.push_str(&format!("{v:.9}f32,"));
        if i % 8 == 7 {
            src.push('\n');
        }
    }
    src.push_str("];\n");

    src.push_str("pub const SPECTRAL_MODES: &[(f32, f32, f32, f32, f32)] = &[\n");
    for mode in &spectral.mode {
        src.push_str(&format!(
            "({:.4}f32, {:.4}f32, {:.4}f32, {:.4}f32, {:.4}f32),\n",
            mode.kx, mode.ky, mode.phase, mode.speed, mode.weight
        ));
    }
    src.push_str("];\n");

    src.push_str("pub const GENERATED_VARIANTS: &[(&str, &str, &str, f32)] = &[\n");
    for v in &anims.variant {
        src.push_str(&format!(
            "({:?}, {:?}, {:?}, {:.4}f32),\n",
            v.name, v.kernel, v.palette, v.weight
        ));
    }
    src.push_str("];\n");

    src.push_str("pub const GENERATED_PALETTES: &[(&str, &[[u8; 3]])] = &[\n");
    for p in &palettes.palette {
        let cols: Vec<String> = p
            .colors
            .iter()
            .map(|c| {
                let [r, g, b] = parse_hex(c);
                format!("[{r}, {g}, {b}]")
            })
            .collect();
        src.push_str(&format!("({:?}, &[{}]),\n", p.name, cols.join(", ")));
    }
    src.push_str("];\n");

    fs::write(out, src).expect("write generated tables");
}
